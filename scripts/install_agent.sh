#!/usr/bin/env bash
# Install (or redeploy) the native launchd agent that runs the departure-sign
# proxy on the Mac mini. Replaces the retired Docker path — see
# docs/proposals/native-launchd-transit-tracker.md.
#
#   scripts/install_agent.sh [--clean]
#
# --clean rebuilds the venv from scratch (the equivalent of `docker build`
# from no cache, which the container path gave us for free).
#
# Staging is deliberate: app/ is a copy on the INTERNAL disk. launchd agents
# have no Full Disk Access and macOS TCC denies them reads under /Volumes/*,
# and /Volumes/dev has wedged repeatedly (infra#25).
set -euo pipefail

LABEL="org.eastsideurbanism.transit-tracker"
RUNTIME_DIR="${TT_RUNTIME_DIR:-$HOME/.local/share/transit-tracker}"
APP_DIR="$RUNTIME_DIR/app"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
LOG="$HOME/Library/Logs/transit-tracker.log"
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CLEAN=0
[ "${1:-}" = "--clean" ] && CLEAN=1

command -v uv >/dev/null || { echo "FATAL: uv not on PATH" >&2; exit 1; }
[ -d "$RUNTIME_DIR/config" ] || { echo "FATAL: $RUNTIME_DIR/config missing — seed it with scripts/sync_runtime.sh" >&2; exit 1; }

if [ "$SRC_DIR" = "$APP_DIR" ]; then
  # Running from inside the deployed copy (the mini keeps a clone there and
  # pulls in place). Staging would be rsync onto itself with --delete.
  echo "==> already in $APP_DIR, skipping staging"
else
  echo "==> staging $SRC_DIR -> $APP_DIR"
  mkdir -p "$APP_DIR"
  rsync -a --delete \
    --exclude .git --exclude .venv --exclude __pycache__ --exclude notebooks \
    "$SRC_DIR"/ "$APP_DIR"/
fi

echo "==> building venv"
cd "$APP_DIR"
[ "$CLEAN" = 1 ] && rm -rf .venv
uv sync --frozen --no-dev --no-editable

# --no-editable matters: under an editable install `_PROJECT_ROOT` is the
# checkout, so service.yaml and the GTFS index would resolve back into it
# rather than the runtime dir the env vars below point at.

echo "==> writing $PLIST"
mkdir -p "$(dirname "$PLIST")" "$(dirname "$LOG")"
cat > "$PLIST" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/install_agent.sh — edit the script, not this file. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$APP_DIR/.venv/bin/python</string>
    <string>-m</string><string>transit_tracker.cli</string>
    <string>service</string>
  </array>
  <key>WorkingDirectory</key><string>$APP_DIR</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key><string>/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    <key>HOME</key><string>$HOME</string>
    <key>TZ</key><string>America/Los_Angeles</string>
    <key>PYTHONUNBUFFERED</key><string>1</string>
    <key>SERVICE_SETTINGS_PATH</key><string>$RUNTIME_DIR/config/service.yaml</string>
    <key>PROFILES_DIR</key><string>$RUNTIME_DIR/config</string>
    <key>GTFS_DB_PATH</key><string>$RUNTIME_DIR/data/gtfs_index.sqlite</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <!-- Dict, not <true/>: a bare KeepAlive also revives the job after a
       deliberate \`launchctl stop\`, which turns maintenance into a fight.
       This is \`--restart=always\` semantics without that. -->
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/><key>Crashed</key><true/></dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <!-- Interactive opts out of the I/O + CPU throttling macOS applies to
       Standard background jobs; this pushes to a wall display every 30 s. -->
  <key>ProcessType</key><string>Interactive</string>
  <key>StandardOutPath</key><string>$LOG</string>
  <key>StandardErrorPath</key><string>$LOG</string>
</dict>
</plist>
PLIST_EOF
plutil -lint "$PLIST" >/dev/null

echo "==> loading"
domain="gui/$(id -u)"
launchctl bootout "$domain/$LABEL" 2>/dev/null || true
# bootstrap fails with `5: Input/output error` over ssh; `load -w` is the
# fallback. Neither exit code can be trusted, so the state is asserted below —
# a silently-unloaded agent here is a blank sign (rgs#181).
launchctl bootstrap "$domain" "$PLIST" 2>/dev/null || launchctl load -w "$PLIST"
if ! launchctl list | grep -q "$LABEL"; then
  echo "FATAL: $LABEL is not loaded after install — the sign is dark." >&2
  exit 1
fi
echo "OK: $LABEL loaded"
echo
echo "Verify (the last one is the only one that proves the *sign* works):"
echo "  launchctl list | grep $LABEL"
echo "  lsof -nP -iTCP:8000 -sTCP:LISTEN"
echo "  curl -o /dev/null -w '%{http_code}\\n' localhost:8080/transit-tracker"
echo "  grep 'Push to' $LOG | tail -1"
